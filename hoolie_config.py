def get_hoolie_price(pet_type, plan, weight_category, breed=None):
    """
    Calculate Hoolie insurance price based on pet type, plan, weight, and breed.

    Args:
        pet_type: "dog" or "cat"
        plan: "Silver", "Gold", or "Platinum Dynasty"
        weight_category: Weight category string (e.g., "έως 10 κιλά")
        breed: Dog breed name (for surcharge calculation)

    Returns:
        Final price in euros
    """
    plans = HOOLIE_DOG_PLANS if pet_type == "dog" else HOOLIE_CAT_PLANS

    if plan not in plans:
        raise ValueError(f"Invalid plan: {plan}")

    base_price = plans[plan]["price_by_weight"].get(weight_category)

    if base_price is None:
        raise ValueError(f"Invalid weight category: {weight_category}")

    # Apply breed surcharge for dogs
    if pet_type == "dog" and breed:
        if breed in HOOLIE_DOG_BREED_SURCHARGES["5%"]:
            base_price *= 1.05
        elif breed in HOOLIE_DOG_BREED_SURCHARGES["20%"]:
            base_price *= 1.20

    return round(base_price, 2)


def format_hoolie_coverage_table(plan_data):
    """Format Hoolie coverage data for PDF/email display."""
    lines = []
    for key, value in plan_data["coverage"].items():
        lines.append(f"• {key}: {value}")
    return "\n".join(lines)